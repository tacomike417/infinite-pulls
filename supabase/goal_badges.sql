on conflict (name) do update
  set description  = excluded.description,
      icon         = excluded.icon,
      badge_image  = excluded.badge_image,
      badge_text   = excluded.badge_text,
      goal_type    = excluded.goal_type,
      config       = excluded.config,
      enabled      = excluded.enabled;


-- ============================================================
-- 5. CHECK — the goals carrying artwork, in board order.
-- ============================================================
select display_order, name, goal_type, badge_image, enabled
  from public.collector_goal_templates
 where badge_image is not null
 order by display_order;
