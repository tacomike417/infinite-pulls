   'graded_count', '{"grade":10,"target":10}'::jsonb, 11, true),

  ('Grade Ladder',
   'Own the same card in every grade from 1 through 10.',
   '🪜', 'assets/goal-badges/grade-ladder.webp', '🏆 Grade Ladder',
   'grade_ladder', '{}'::jsonb, 12, true),

  ('Monthly Momentum',
   'Add 25 different cards to your collection in one calendar month.',
   '📅', 'assets/goal-badges/monthly-momentum.webp', '🏆 Monthly Momentum',
   'added_in_month', '{"target":25}'::jsonb, 13, true),

  ('Yearlong Collector',
   'Add at least one card every month for twelve months in a row.',
   '🗓️', 'assets/goal-badges/yearlong-collector.webp', '🏆 Yearlong Collector',
   'monthly_streak', '{"months":12}'::jsonb, 14, true),

  ('Value Milestone',
